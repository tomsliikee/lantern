#!/usr/bin/env node
// Generates the extension's colour and type values from the design system,
// so no value is typed by hand: extension/lib/tokens.js for drawing code and
// extension/stylesheet.css from tools/stylesheet.template.css.
//
// St has no CSS custom properties, so the template is written once with
// $token placeholders and expanded into one rule set per scheme (light, dark).

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const system = JSON.parse(fs.readFileSync(path.join(root, 'insights-mono', 'tokens.json'), 'utf8'));
// The tinted themes of the design system are not used.
const THEMES = ['light', 'dark'];

function resolveColor(name, theme, seen = new Set()) {
    const token = system.color.tokens.find(t => t.name === name);
    if (!token || seen.has(name))
        throw new Error(`Unknown or circular colour token: ${name}`);
    seen.add(name);
    const value = typeof token.value === 'string' ? token.value : token.value[theme];
    const reference = /^\{(.+)\}$/.exec(value);
    return reference ? resolveColor(reference[1], theme, seen) : value;
}

// A scheme is one theme, "light" or "dark".
const colors = Object.fromEntries(THEMES.map(theme =>
    [theme, Object.fromEntries(system.color.tokens.map(t => [t.name, resolveColor(t.name, theme)]))]));

const px = value => Number.parseFloat(value);
const scale = group => Object.fromEntries(group.tokens.map(t => [t.name, px(t.value)]));
const sizes = {...scale(system.spacing), ...scale(system.radius), ...scale(system.size)};

// Only the serif and sans groups; the Flex group is not used. The tracking
// is the letter-spacing in pixels.
const type = Object.fromEntries(system.type.groups
    .filter(group => group.family === 'serif' || group.family === 'sans')
    .flatMap(group => group.styles.map(style => [style.name, {
        size: px(style.fontSize),
        line: px(style.lineHeight),
        weight: style.fontWeight,
        tracking: style.letterSpacing ? px(style.letterSpacing) : 0,
        serif: group.family === 'serif',
    }])));

// The design system's stacks, ending in a generic family so that a missing
// font never leaves the panel without text.
const family = 'Inter, sans-serif';
const serifFamily = 'Geist Serif, serif';
const header = '// Generated by tools/build-tokens.js from insights-mono/tokens.json. Do not edit.\n';

fs.writeFileSync(path.join(root, 'extension', 'lib', 'tokens.js'), `${header}
export const family = ${JSON.stringify(family)};

export const serifFamily = ${JSON.stringify(serifFamily)};

export const colors = ${JSON.stringify(colors, null, 4)};

export const sizes = ${JSON.stringify(sizes, null, 4)};

export const type = ${JSON.stringify(type, null, 4)};
`);

const template = fs.readFileSync(path.join(__dirname, 'stylesheet.template.css'), 'utf8');

// Rules above the marker carry no colour and are written once.
const [shared, themed] = template.split('/* themed */');

// The same code fills the template in here and for any later use.
import('../extension/lib/sheet.js').then(({expand, schemeSheet}) => {
    const sheets = Object.keys(colors).map(scheme => schemeSheet(themed, scheme, sizes, colors[scheme]));
    fs.writeFileSync(path.join(root, 'extension', 'stylesheet.css'),
        `${header.replace('//', '/*').replace('\n', ' */\n')}\n${expand(shared, sizes).trim()}\n\n${sheets.join('\n\n')}\n`);
});
